import { createHash } from 'node:crypto'
import { basename, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { cp, mkdir, mkdtemp, readFile, rename, rm, stat, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { unzipSync } from 'fflate'
import {
  buildFileInventory, sdkZipLibRelativePath, sdkZipRootPrefix, sha256, validateRequiredFiles,
} from './lib/sdk-integrity.mjs'

const input = process.argv[2]
if (input === undefined) {
  throw new Error('Usage: npm run sync:sdk -- <external.zip|external-directory|lib-directory>')
}

const projectRoot = resolve(new URL('..', import.meta.url).pathname)
const vendorParent = resolve(projectRoot, 'vendor')
const destination = resolve(vendorParent, 'office-sdk')
const temporaryRoot = await mkdtemp(join(tmpdir(), 'bamboo-office-sdk-'))
const stagedVendor = resolve(temporaryRoot, 'office-sdk')
const stagedLib = resolve(stagedVendor, 'lib')
const inputPath = resolve(input)

async function directoryTreeHash(root) {
  const inventory = await buildFileInventory(root)
  return createHash('sha256').update(JSON.stringify(inventory)).digest('hex')
}

async function extractZip(zipPath) {
  const body = await readFile(zipPath)
  const entries = unzipSync(new Uint8Array(body))
  const rootPrefix = sdkZipRootPrefix(Object.keys(entries))
  const normalizedEntries = new Map()
  for (const [rawName, bytes] of Object.entries(entries)) {
    const normalizedName = rawName.replaceAll('\\', '/')
    if (normalizedEntries.has(normalizedName)) {
      throw new Error(`SDK archive contains duplicate normalized path: ${normalizedName}`)
    }
    normalizedEntries.set(normalizedName, bytes)
    const relativePath = sdkZipLibRelativePath(rawName, rootPrefix)
    if (relativePath === null) continue
    const target = resolve(stagedLib, relativePath)
    const targetRelative = relative(stagedLib, target)
    if (
      targetRelative === ''
      || targetRelative === '..'
      || targetRelative.startsWith(`..${sep}`)
      || isAbsolute(targetRelative)
    ) throw new Error(`Unsafe SDK zip path: ${rawName}`)
    await mkdir(resolve(target, '..'), { recursive: true })
    await writeFile(target, bytes)
  }
  for (const notice of ['legal.txt', 'THIRD_PARTY_NOTICES']) {
    const bytes = normalizedEntries.get(`${rootPrefix}${notice}`)
      ?? normalizedEntries.get(`${rootPrefix}lib/${notice}`)
    if (bytes === undefined) throw new Error(`SDK archive is missing ${notice}`)
    await writeFile(resolve(stagedVendor, notice), bytes)
  }
  return sha256(body)
}

async function copyDirectory(sourcePath) {
  const sourceStat = await stat(sourcePath)
  if (!sourceStat.isDirectory()) throw new Error(`SDK source is not a directory: ${sourcePath}`)
  const nestedLib = resolve(sourcePath, 'lib')
  const sourceLib = await stat(nestedLib).then(value => value.isDirectory() ? nestedLib : sourcePath).catch(() => sourcePath)
  // extractZip writes files into an existing directory, whereas fs.cp expects
  // the destination directory itself not to exist when errorOnExist is enabled.
  await rm(stagedLib, { recursive: true, force: true })
  await cp(sourceLib, stagedLib, { recursive: true, force: false, errorOnExist: true })
  for (const notice of ['legal.txt', 'THIRD_PARTY_NOTICES']) {
    const rootNotice = resolve(sourcePath, notice)
    const libNotice = resolve(sourceLib, notice)
    const sourceNotice = await stat(rootNotice).then(() => rootNotice).catch(() => libNotice)
    await cp(sourceNotice, resolve(stagedVendor, notice))
  }
  return directoryTreeHash(sourceLib)
}

try {
  await mkdir(stagedLib, { recursive: true })
  const inputStat = await stat(inputPath)
  const sourceSha256 = inputStat.isFile() ? await extractZip(inputPath) : await copyDirectory(inputPath)
  const { metadata } = await validateRequiredFiles(stagedLib)
  const files = await buildFileInventory(stagedLib)
  const lock = {
    formatVersion: 1,
    sdkName: metadata.name,
    sdkVersion: metadata.version,
    source: basename(inputPath),
    sourceSha256,
    files,
  }
  await writeFile(resolve(stagedVendor, 'LOCK.json'), `${JSON.stringify(lock, null, 2)}\n`)
  const revision = sourceSha256.slice(0, 12)
  const generated = `/** Generated by scripts/sync-office-sdk.mjs. */\nexport const OFFICE_SDK_VERSION = ${JSON.stringify(metadata.version)}\nexport const OFFICE_SDK_REVISION = ${JSON.stringify(revision)}\nexport const OFFICE_SDK_ROUTE_PREFIX = '/bamboo-office-sdk'\nexport const OFFICE_SDK_BASE_PATH = \`\${OFFICE_SDK_ROUTE_PREFIX}/\${OFFICE_SDK_VERSION}-\${OFFICE_SDK_REVISION}\`\n`
  await writeFile(resolve(projectRoot, 'src/office-sdk.generated.ts'), generated)

  await mkdir(vendorParent, { recursive: true })
  const backup = resolve(vendorParent, '.office-sdk-backup')
  await rm(backup, { recursive: true, force: true })
  const hadDestination = await stat(destination).then(() => true).catch(() => false)
  if (hadDestination) await rename(destination, backup)
  try {
    await rename(stagedVendor, destination)
    await rm(backup, { recursive: true, force: true })
  } catch (error) {
    if (hadDestination) await rename(backup, destination)
    throw error
  }
  console.log(`Synced Office SDK ${metadata.version}: ${files.length} files`)
} finally {
  await rm(temporaryRoot, { recursive: true, force: true })
}
